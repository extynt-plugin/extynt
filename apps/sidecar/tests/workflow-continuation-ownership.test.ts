test("stopping a persistent sidecar cancels deferred workflow wakes before closing the store", async (t) => {
  const h = await harness(t);
  const directory = h.sidecar.options.stateDirectory;
  assert.ok(directory);
  t.mock.timers.enable({ apis: ["setTimeout"] });
  h.sidecar.onWorkflowSettlement("no-pending-plan");
  h.sidecar.deferWorkflowDrain();
  await h.sidecar.stop();
  const history = readFileSync(join(directory, "workflow-store.json"));
  assert.doesNotThrow(() => t.mock.timers.tick(35), "a deferred wake must not enter the closed durable store");
  assert.deepEqual(readFileSync(join(directory, "workflow-store.json")), history);
  assert.deepEqual(h.continuationOwners, []);
  assert.equal(h.sidecar.workflowSchedulerRunning, false);
});

test("a provider rejection after sidecar stop cannot append to its closed workflow store", async (t) => {
  let rejectContinuation: (reason: Error) => void = () => { throw new Error("continuation gate was not initialized"); };
  const continuationGate = new Promise<never>((_resolve, reject) => { rejectContinuation = reject; });
  const h = await harness(t, { continuationGate });
  assert.equal((await h.post("/v1/chat", { requestId: "ownership-stop-pending-provider", message: "rename to Hero", autoApply: false })).status, 200);
  const batch = await claimBatch(h);
  assert.equal((await h.post("/v1/snapshots", mutableSnapshot("stop-pending-provider-snapshot", ["layer-1"], "Hero"))).status, 201);
  assert.equal((await h.post("/v1/receipts", verifiedBody(batch, "stop-pending-provider-verified"))).status, 201);
  assert.equal(await h.sidecar.waitUntil(() => h.continuationOwners.length === 1, 2), true, "the continuation must be waiting inside the provider before stop");
  const run = h.sidecar.workflowRuns.get(batch.jobId);
  assert.ok(run); assert.equal(run.state, "running");
  const directory = h.sidecar.options.stateDirectory;
  assert.ok(directory);
  await h.sidecar.stop();
  const history = readFileSync(join(directory, "workflow-store.json"));
  assert.equal(run.controller.signal.aborted, true);
  rejectContinuation(new Error("synthetic late provider rejection after shutdown"));
  await pause(35);
  assert.deepEqual(readFileSync(join(directory, "workflow-store.json")), history, "late provider callbacks preserve shutdown history bytes");
  assert.equal(h.sidecar.workflowSchedulerRunning, false);
  assert.equal(h.sidecar.workflowRuns.size, 0);
});
