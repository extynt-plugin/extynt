test("cancelling a live chat cannot release an executing batch or its unresolved native reservation", async (t) => {
  const h = await harness(t, { providerFailure: true });
  const chat = beginChat(h, "ownership-native-pending");
  const batch = await claimBatch(h);
  const reservation = await h.post("/v1/native-bridge/reserve", { requestId: batch.planId, kind: "mutation" });
  assert.equal(reservation.status, 200);
  const lease = decodeOrThrow(jsonObject, fieldOf(await readJson(reservation), "lease"));
  assert.equal((await h.post("/v1/snapshots", mutableSnapshot("native-pending-snapshot", ["layer-1"], "Hero"))).status, 201);
  assertNoCompetingRecovery(h, batch);
  const replacement = await h.post("/v1/chat", { requestId: "native-pending-replacement", message: "summarize the selected project" });
  assert.equal(replacement.status, 409);
  assert.equal(textOf(await readJson(replacement), "error.code"), "WORKFLOW_ENGINE_BUSY");
  await chat;
  const state = h.sidecar.workflowCoordinator.workflowStore.getState();
  assert.equal(state.activeDispatchLease?.batchId, batch.batchId);
  assert.equal(h.sidecar.nativeBridge.accessQuarantine()?.state, "unresolved");
  const successor = await h.post("/v1/native-bridge/reserve", { requestId: "forbidden-successor", kind: "read" });
  assert.equal(successor.status, 409);
  const wrong = await h.post("/v1/native-bridge/settle", { lease: { ...lease, settlementToken: "wrong" }, outcome: "callback-received" });
  assert.equal(wrong.status, 409);
  assert.equal(h.sidecar.nativeBridge.accessQuarantine()?.state, "unresolved");
  assert.equal((await h.post("/v1/native-bridge/settle", { lease, outcome: "callback-received" })).status, 200);
  assert.equal(h.sidecar.workflowCoordinator.workflowStore.getState().activeDispatchLease?.batchId, batch.batchId, "a bridge callback alone is not a verified host receipt");
  assert.equal((await h.post("/v1/receipts", verifiedBody(batch, "native-pending-late-verified"))).status, 201);
  assert.equal(h.sidecar.workflowCoordinator.workflowStore.getState().jobs[batch.jobId]?.status, "cancelled", "late evidence must never reopen cancelled authoring");
  assert.equal(h.sidecar.workflowContinuationQueue.has(batch.jobId), false);
});

test("a newer executing batch and native uncertainty prevent restart from resuming an older verified batch", async (t) => {
  const h = await harness(t, { cycles: 1 });
  const chat = beginChat(h, "ownership-restart-order", false);
  const first = await claimBatch(h);
  assert.equal((await h.post("/v1/snapshots", mutableSnapshot("restart-first-applied", ["layer-1"], "Hero"))).status, 201);
  assert.equal((await h.post("/v1/receipts", verifiedBody(first, "restart-first-verified"))).status, 201);
  assert.equal((await chat).status, 200);
  const second = await claimBatch(h);
  assert.notEqual(second.batchId, first.batchId); assert.equal(second.jobId, first.jobId);
  const reservation = await h.post("/v1/native-bridge/reserve", { requestId: second.planId, kind: "mutation" });
  assert.equal(reservation.status, 200);
  await h.sidecar.stop();
  const directory = h.sidecar.options.stateDirectory;
  assert.ok(directory);
  const ledgerPath = join(directory, "workflow-store.json");
  const history = readFileSync(ledgerPath);
  const restarted = sidecarFor({ port: 0, token, stateDirectory: directory, chatProvider: new MockProvider({ script: mockAgentScript }), quietAgentLog: true, workflowMaxCycles: 1 });
  const address = await restarted.start(); t.after(() => restarted.stop());
  assert.deepEqual(readFileSync(ledgerPath), history, "construction preserves the unsettled durable history");
  const snapshot = await fetch(`http://${address.host}:${address.port}/v1/snapshots`, { method: "POST", headers: { ...authorization, "content-type": "application/json" }, body: JSON.stringify(mutableSnapshot("restart-fresh-observation", ["layer-1"], "Hero")) });
  assert.equal(snapshot.status, 201);
  assert.equal(restarted.nativeBridge.accessQuarantine()?.state, "unresolved");
  assert.equal(restarted.workflowContinuationQueue.size, 0);
  assert.equal(restarted.workflowSchedulerRunning, false);
  assert.equal(restarted.workflowCoordinator.batchForPlan(first.planId)?.verification.state, "verified");
  assert.notEqual(restarted.workflowCoordinator.batchForPlan(second.planId)?.verification.state, "verified");
  const mailbox = await claimResponse(restarted);
  assert.equal(mailbox.status, 409, "the uncertain newer batch must prevent native mailbox access after restart");
  assert.equal(textOf(await readJson(mailbox), "error.code"), "HOST_NATIVE_UNRESOLVED");
});

test("an exact late receipt wakes its retained waiting run once and duplicate evidence never reopens it", async (t) => {
  const h = await harness(t, { providerFailure: true });
  const response = await h.post("/v1/chat", { requestId: "ownership-late", message: "rename to Hero", autoApply: false });
  assert.equal(response.status, 200);
  assert.equal(textOf(await readJson(response), "outcome"), "planned");
  const batch = await claimBatch(h);
  assert.equal(h.sidecar.workflowRuns.get(batch.jobId)?.state, "waiting_receipt");
  assert.equal((await h.post("/v1/snapshots", mutableSnapshot("ownership-late-snapshot", ["layer-1"], "Hero"))).status, 201);
  assert.equal(h.sidecar.workflowRuns.get(batch.jobId)?.state, "waiting_receipt", "a snapshot supplies no execution receipt");
  const receipt = verifiedBody(batch, "ownership-late-verified");
  assert.equal((await h.post("/v1/receipts", receipt)).status, 201);
  assert.equal(await h.sidecar.waitUntil(() => h.sidecar.workflowCoordinator.workflowStore.getState().jobs[batch.jobId]?.status === "blocked", 2), true);
  assert.equal(h.sidecar.workflowCoordinator.workflowStore.getState().jobs[batch.jobId]?.providerCycle, 2);
  const events = h.sidecar.workflowCoordinator.workflowStore.listEvents(batch.jobId);
  assert.equal((await h.post("/v1/receipts", receipt)).status, 200);
  assert.deepEqual(h.sidecar.workflowCoordinator.workflowStore.listEvents(batch.jobId), events);
  assert.equal(h.sidecar.workflowContinuationQueue.has(batch.jobId), false);
  assert.equal(h.sidecar.workflowRuns.get(batch.jobId)?.state, "terminal");
  assert.equal(events.filter((event) => event.type === "batch.executing").length, 1);
  assert.equal(events.filter((event) => event.type === "batch.receipt").length, 1);
});

test("terminal cleanup retires only the obsolete queued job and retains another job awaiting a receipt", async (t) => {
  const h = await harness(t, { providerFailure: true });
  const firstChat = beginChat(h, "ownership-terminal-old");
  const first = await claimBatch(h);
  await h.post("/v1/snapshots", mutableSnapshot("ownership-terminal-old-snapshot", ["layer-1"], "Hero"));
  assert.equal((await h.post("/v1/receipts", verifiedBody(first, "ownership-terminal-old-verified"))).status, 201);
  assert.equal((await firstChat).status, 200);
  const secondChat = await h.post("/v1/chat", { requestId: "ownership-retained-waiting", message: "rename to Newer", autoApply: false });
  assert.equal(secondChat.status, 200);
  const secondPlan = h.sidecar.readyPlans.find((plan) => plan.requestId === "ownership-retained-waiting");
  assert.ok(secondPlan);
  const secondJobId = h.sidecar.workflowCoordinator.jobIdForPlan(secondPlan.planId);
  assert.ok(secondJobId);
  const waiting = h.sidecar.workflowRuns.get(secondJobId);
  assert.ok(waiting); assert.equal(waiting.state, "waiting_receipt");
  const oldRun = { ...waiting, controller: new AbortController(), goalSummary: "Rename to Hero", autoApply: true, jobId: first.jobId, requestId: "ownership-terminal-old", state: "scheduled" as const, pendingBatchId: first.batchId, nextCycle: 2 };
  h.sidecar.workflowRuns.set(first.jobId, oldRun);
  h.sidecar.workflowContinuationQueue.add(first.jobId);
  h.sidecar.wakeDeferredWorkflowContinuations();
  assert.equal(h.sidecar.workflowContinuationQueue.has(first.jobId), false);
  assert.equal(h.sidecar.workflowRuns.get(first.jobId)?.state, "terminal");
  assert.equal(h.sidecar.workflowRuns.get(secondJobId), waiting, "cleanup must retain the unrelated waiting identity");
  assert.equal(waiting.state, "waiting_receipt");
  assert.equal(waiting.controller.signal.aborted, false, "retiring an obsolete run cannot abort the retained run's independent controller");
  assert.equal(h.sidecar.workflowCoordinator.batchForPlan(first.planId)?.verification.state, "verified");
  assert.equal(h.sidecar.workflowCoordinator.workflowStore.getState().jobs[secondJobId]?.status, "active");
});

test("a stale finish callback cannot clear a newer turn's progress even when request IDs repeat", async (t) => {
  const h = await harness(t);
  const older = { requestId: "ownership-reused-id", controller: new AbortController(), startedAt: 1, settled: Promise.resolve() };
  const newer = { ...older, controller: new AbortController(), startedAt: 2 };
  const progress = { requestId: newer.requestId, step: 1, maxSteps: 60, phase: "note", label: "newer turn", notes: ["newer turn"], at: new Date().toISOString() };
  const authoring = { requestId: newer.requestId, progress: { planId: "newer-plan", jobId: null, operations: 1, batches: 1, sealed: false, label: "newer authoring", at: progress.at } };
  h.sidecar.activeChatTurn = newer;
  h.sidecar.chatProgress.set(newer.requestId, progress);
  h.sidecar.chatSteering.set(newer.requestId, ["newer steering"]);
  h.sidecar.reviewHeldRequests.add(newer.requestId);
  h.sidecar.chatAuthoring = authoring;
  let settled = 0;
  h.sidecar.finishChatTurn(older.requestId, { turn: older, markSettled: () => { settled += 1; } });
  assert.equal(settled, 1, "the stale owner can acknowledge only its own settlement");
  assert.equal(h.sidecar.activeChatTurn, newer);
  assert.equal(h.sidecar.chatProgress.get(newer.requestId), progress);
  assert.deepEqual(h.sidecar.chatSteering.get(newer.requestId), ["newer steering"]);
  assert.equal(h.sidecar.reviewHeldRequests.has(newer.requestId), true);
  assert.equal(h.sidecar.chatAuthoring, authoring);
});

test("an unknown execution reconciles before native settlement and wakes once after the exact ACK without another snapshot", async (t) => {
  const h = await harness(t, { providerFailure: true });
  assert.equal((await h.post("/v1/chat", { requestId: "ownership-receipt-before-ack", message: "rename to Hero", autoApply: false })).status, 200);
  const batch = await claimBatch(h);
  const reservation = await h.post("/v1/native-bridge/reserve", { requestId: batch.planId, kind: "mutation" });
  assert.equal(reservation.status, 200);
  const lease = decodeOrThrow(jsonObject, fieldOf(await readJson(reservation), "lease"));
  assert.equal((await h.post("/v1/panel/events", { code: "HOST_NATIVE_UNRESOLVED", message: "synthetic callback timeout", nativeLease: { requestId: batch.planId, kind: "mutation", code: "HOST_TIMEOUT" } })).status, 201);
  assert.equal(h.sidecar.failUnsettledPlan(batch.planId, "HOST_TIMEOUT", "synthetic watchdog observed no host callback", true), true);
  assert.equal(h.sidecar.workflowCoordinator.batchForPlan(batch.planId)?.execution.state, "unknown", "the actual watchdog projection retains execution uncertainty");
  assert.equal(h.sidecar.workflowRuns.get(batch.jobId)?.state, "waiting_receipt");
  assert.equal((await h.post("/v1/snapshots", mutableSnapshot("receipt-before-ack-snapshot", ["layer-1"], "Hero"))).status, 201);
  const receipt = verifiedBody(batch, "receipt-before-ack-verified");
  assert.equal((await h.post("/v1/receipts", receipt)).status, 201);
  await pause(35);
  assert.equal(h.sidecar.nativeBridge.accessQuarantine()?.state, "unresolved");
  assert.equal(h.sidecar.workflowRuns.get(batch.jobId)?.state, "waiting_receipt");
  assert.deepEqual(h.continuationOwners, [], "even the deferred receipt wake must respect the held physical lease");
  assert.equal((await h.post("/v1/native-bridge/settle", { lease, outcome: "callback-received" })).status, 200);
  assert.equal(await h.sidecar.waitUntil(() => h.sidecar.workflowCoordinator.workflowStore.getState().jobs[batch.jobId]?.providerCycle === 2, 2), true, "exact lease release supplies the missing wake without another snapshot");
  assert.equal(await h.sidecar.waitUntil(() => h.sidecar.workflowRuns.get(batch.jobId)?.state === "terminal", 2), true);
  assert.deepEqual(h.continuationOwners, [undefined]);
  const events = h.sidecar.workflowCoordinator.workflowStore.listEvents(batch.jobId);
  assert.equal((await h.post("/v1/receipts", receipt)).status, 200);
  await pause(25);
  assert.deepEqual(h.continuationOwners, [undefined]);
  assert.deepEqual(h.sidecar.workflowCoordinator.workflowStore.listEvents(batch.jobId), events);
  assert.equal(events.filter((event) => event.type === "batch.executing").length, 1);
  assert.equal(events.filter((event) => event.type === "batch.receipt").length, 1);
  assert.equal(events.filter((event) => event.type === "batch.reconciled").length, 1);
});

